/** Projeto de teste com N slides: Capa, Conteúdo repetido (numerado 02, 03…) e CTA no fim. */
export function projetoTeste(n = 3): Pick<Projeto, 'nome' | 'slides' | 'faixaOverrides'> {
  const tipos = n <= 1 ? ['capa'] : ['capa', ...Array.from({ length: Math.max(0, n - 2) }, () => 'conteudo'), 'cta'];
  return {
    nome: 'Prompt bonito não paga boleto',
    slides: tipos.map((tipoId, i) => {
      const overrides: Record<string, Record<string, unknown>> = tipoId === 'conteudo'
        ? { num: { texto: String(i + 1).padStart(2, '0') } }
        : {};
      return { id: `s${i + 1}`, tipoId, conteudo: {}, overrides };
    }),
    faixaOverrides: {},
  };
}

export const PROJETO_TESTE = projetoTeste(3);
